-- ============================================================
-- 금칙어 목록 튜닝 — 오탐 제거 + 초성 매칭 + 표현 보강
--   (음식/일상 리뷰에서 정상어를 막던 단어 제거)
-- ============================================================

-- 1) 정규화가 한글 자모(초성/중성)도 보존하도록 개선 → 'ㅅㅂ' 같은 초성 욕설 매칭.
--    (기존: 가-힣만 유지 → 자모는 제거돼 초성 욕설을 못 걸렀음)
create or replace function public.normalize_text(t text)
returns text as $$
  select regexp_replace(lower(coalesce(t, '')), '[^0-9a-z가-힣ㄱ-ㅎㅏ-ㅣ]', '', 'g');
$$ language sql immutable;

-- 2) 오탐 위험 단어 제거(음식/일상 리뷰에서 정상 사용).
--    보지/자지/꺼져(동사 활용), 새끼(강아지 새끼), 니미(어절 결합 오탐)
delete from public.banned_words
 where word in ('보지', '자지', '꺼져', '새끼', '니미');

-- 3) 안전한 대체·보강 표현 추가(초성 포함).
insert into public.banned_words (word) values
  ('개새끼'), ('새끼야'), ('니미럴'),
  ('미친놈'), ('미친년'), ('존나'), ('개소리'),
  ('닥쳐'), ('좆같'), ('썅'), ('개같'),
  ('ㅅㅂ'), ('ㅄ'), ('ㅂㅅ'), ('ㅈㄹ'), ('ㅆㅂ')
on conflict (word) do nothing;
